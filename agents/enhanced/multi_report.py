# ── Minimal markdown→HTML converter ────────────────────────────────────────────
# The LLM may still output markdown even after we tell it to output HTML.
# This converter handles the most common patterns before the text goes into
# the final HTML wrapper. It is NOT a full markdown parser — just enough
# to clean up the output the LLM actually produces.
def _strip_outer_html_document(text: str) -> str:
    """If the LLM emitted a full <!DOCTYPE>...<html>...<body>...</body></html>
    document (because the prompt asked for HTML), extract just the body content
    so it can be safely embedded inside the synthesizer's outer document.

    Strategy:
    - Find the <body> tag; everything from there until </body> (or end) is kept.
    - If there's no <body> tag but the text starts with <html>, drop up to <html>.
    - If neither is present, return text as-is.
    """
    if not text:
        return text
    lower = text.lower()
    body_start = lower.find("<body")
    if body_start != -1:
        # Advance past the opening <body ...> tag
        tag_end = lower.find(">", body_start)
        if tag_end == -1:
            return text  # malformed, leave alone
        after_body = text[tag_end + 1:]
        # Find matching </body>
        body_end = lower.rfind("</body>")
        if body_end != -1 and body_end > tag_end:
            return after_body[: body_end - (tag_end + 1)].strip()
        return after_body.strip()
    # No <body>; if there's an <html> opener near start, drop up to it
    html_idx = lower.find("<html")
    if html_idx != -1 and html_idx < 200:
        tag_end = lower.find(">", html_idx)
        if tag_end != -1:
            return text[tag_end + 1 :].replace("</html>", "").strip()
    return text


def _markdown_to_html(text: str) -> str:
    """Convert common markdown patterns to HTML so a markdown draft renders correctly."""
    if not text:
        return text
    lines = text.splitlines(keepends=True)
    out_lines = []
    in_ul = in_ol = False
    i = 0
    while i < len(lines):
        line = lines[i]
        # Horizontal rule
        if re.match(r"^-{3,}|^\*{3,}$", line.strip()):
            if in_ul: out_lines.append("</ul>"); in_ul = False
            if in_ol: out_lines.append("</ol>"); in_ol = False
            out_lines.append("<hr>")
            i += 1; continue
        # Heading
        m = re.match(r"^(#{1,6})\s+(.*)$", line)
        if m:
            if in_ul: out_lines.append("</ul>"); in_ul = False
            if in_ol: out_lines.append("</ol>"); in_ol = False
            level = len(m.group(1))
            out_lines.append(f"<h{level}>{m.group(2).strip()}</h{level}>")
            i += 1; continue
        # Unordered list item
        m = re.match(r"^[-*+]\s+(.*)$", line)
        if m:
            if not in_ul:
                if in_ol: out_lines.append("</ol>"); in_ol = False
                out_lines.append("<ul>"); in_ul = True
            out_lines.append(f"<li>{m.group(1)}</li>")
            i += 1; continue
        # Ordered list item
        m = re.match(r"^\d+\.\s+(.*)$", line)
        if m:
            if not in_ol:
                if in_ul: out_lines.append("</ul>"); in_ul = False
                out_lines.append("<ol>"); in_ol = True
            out_lines.append(f"<li>{m.group(1)}</li>")
            i += 1; continue
        # Blank line
        if re.match(r"^\s*$", line):
            if in_ul: out_lines.append("</ul>"); in_ul = False
            if in_ol: out_lines.append("</ol>"); in_ol = False
            out_lines.append(line)
            i += 1; continue
        # Paragraph / inline text
        if in_ul: out_lines.append("</ul>"); in_ul = False
        if in_ol: out_lines.append("</ol>"); in_ol = False
        text_content = line.rstrip()
        # Bold
        text_content = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text_content)
        # Italic
        text_content = re.sub(r"\*(.+?)\*", r"<em>\1</em>", text_content)
        # Inline code
        text_content = re.sub(r"`(.+?)`", r"<code>\1</code>", text_content)
        # Links [text](url)
        text_content = re.sub(r"\[(.+?)\]\(.+?\)", r"\1", text_content)
        if text_content.strip():
            out_lines.append(f"<p>{text_content}</p>")
        else:
            out_lines.append(text_content)
        i += 1
    if in_ul: out_lines.append("</ul>")
    if in_ol: out_lines.append("</ol>")
    return "".join(out_lines)

