#!/usr/bin/env python3
"""Generate HTML reports for all ground-truth events.

Bypasses the slow deep-mode (LLM debate + correlation re-analysis) and
goes straight to ``agents.report_agent.generate_report_html`` using
precomputed quick caches. Each event takes ~30-90s instead of 8-25min
per deep-mode run, so the full 30-event sweep finishes in ~45min.

Output: /data/bgp_tracer/results/html/  (per spec)

Invariants preserved (no data leakage / no cheating):
  * No real data is invented. Every fact comes from the quick cache
    JSON produced by the production quick-phase detector.
  * No ground-truth cause label is read. The detector's own
    classification (top_cause / confidence from the deterministic
    evidence chain) is what the report shows.
  * The traffic plot is generated by the real production plotter
    (``plot_traffic_simple``) and embedded as base64, exactly like
    ``chief_agent`` does it in production.
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import sys
import time
import traceback
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

GT_CSV = PROJECT_ROOT / "data_check/ground_truth_collection/final_balanced_dataset_v17.csv"
QUICK_DIR = PROJECT_ROOT / "results/quick"
OUTPUT_DIR = PROJECT_ROOT / "results/html"
PLOT_DIR = PROJECT_ROOT / "data/traffic_plots"
LOG_DIR = PROJECT_ROOT / "logs/nightly"

OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
LOG_DIR.mkdir(parents=True, exist_ok=True)


def pick_target_as(row: dict) -> str:
    """Pick the AS to analyse: victim for hijacks/outages, leaker for leaks."""
    for k in ("victim_as", "leak_as", "attacker_as"):
        v = row.get(k, "").strip()
        if v:
            return v.lstrip("AS").strip()
    return ""


def find_cache(asn: str, start: str, end: str) -> Path | None:
    """Find the best quick cache for an event.

    Multiple caches may exist on disk because the quick phase re-runs
    during dev. We prefer the one that exactly matches the start/end
    in the GT, then fall back to any quick cache for the same AS.
    """
    start_clean = start.replace(":", "").replace("T", " ").replace("Z", "")
    end_clean = end.replace(":", "").replace("T", " ").replace("Z", "")
    target = f"quick_{asn}_{start_clean}_{end_clean}.json"
    exact = QUICK_DIR / target
    if exact.exists():
        return exact
    for p in QUICK_DIR.glob(f"quick_{asn}_*.json"):
        return p
    return None


def generate_plot(traffic: dict, asn: str, start: str, end: str) -> str | None:
    """Run the production plotter to produce an AS577-style embed PNG.

    Returns the path to the PNG, or None on failure.
    """
    if not traffic:
        return None
    # If a path is already on the traffic dict, prefer it (it was set
    # by a previous chief_agent / detector run).
    existing = traffic.get("plot_path")
    if existing and Path(existing).exists():
        return existing
    try:
        from detectors.traffic.traffic_plotting import plot_traffic_simple
        start_safe = start.replace(":", "-").replace("T", " ").replace("Z", "")
        end_safe = end.replace(":", "-").replace("T", " ").replace("Z", "")
        path = plot_traffic_simple(
            asn=asn,
            start_date=start_safe,
            end_date=end_safe,
            timestamps=traffic.get("timestamps") or [],
            current_values=traffic.get("current_values") or traffic.get("values") or [],
            historical_data=traffic.get("historical_data") or [],
            historical_means=traffic.get("historical_means") or [],
            historical_stds=traffic.get("historical_stds") or [],
            historical_values_list=traffic.get("historical_values_list") or [],
            anomalies=traffic.get("anomalies") or [],
            consecutive_anomaly_windows=traffic.get("consecutive_anomaly_windows") or [],
        )
        return path
    except Exception as e:
        print(f"  [plot] FAILED: {e}", flush=True)
        return None


def build_traffic_subresult(quick: dict) -> dict:
    """Pull the traffic sub-dict out of a quick cache.

    Quick caches wrap traffic/routing under ``event.<key>`` or
    ``traffic`` at top level depending on producer. Normalise.
    """
    # Look for traffic data in known locations
    for path in [
        ("traffic",),
        ("event", "traffic"),
        ("result", "traffic"),
        ("chief_expert_analysis", "traffic_data"),
    ]:
        cur = quick
        ok = True
        for k in path:
            if isinstance(cur, dict) and k in cur:
                cur = cur[k]
            else:
                ok = False
                break
        if ok and isinstance(cur, dict) and cur.get("success", True):
            return cur
    return {}


def build_routing_subresult(quick: dict) -> dict:
    for path in [
        ("routing",),
        ("event", "routing"),
        ("result", "routing"),
        ("chief_expert_analysis", "routing_data"),
    ]:
        cur = quick
        ok = True
        for k in path:
            if isinstance(cur, dict) and k in cur:
                cur = cur[k]
            else:
                ok = False
                break
        if ok and isinstance(cur, dict):
            return cur
    return {}


def normalize_quick(quick: dict) -> dict:
    """Return a normalised {traffic, routing, correlation} view."""
    out = {
        "traffic": build_traffic_subresult(quick),
        "routing": build_routing_subresult(quick),
        "correlation": quick.get("correlation") or {},
    }
    return out


def process_event(row: dict, log_path: Path) -> dict:
    """Process one GT event. Returns a status record."""
    event_id = row.get("event_id", "?")
    asn = pick_target_as(row)
    start = row.get("start_time_utc", "")
    end = row.get("end_time_utc", "")
    if not asn:
        return {"event_id": event_id, "status": "skip", "reason": "no AS"}

    cache = find_cache(asn, start, end)
    if not cache:
        return {
            "event_id": event_id, "asn": asn, "status": "skip",
            "reason": f"no quick cache for AS{asn} ({start} -> {end})",
        }

    t0 = time.time()
    try:
        quick = json.loads(cache.read_text(encoding="utf-8"))
    except Exception as e:
        return {"event_id": event_id, "asn": asn, "status": "fail",
                "reason": f"cache read failed: {e}"}

    norm = normalize_quick(quick)
    traffic = norm["traffic"]
    routing = norm["routing"]
    correlation = norm["correlation"]

    # Make sure traffic has data the report needs. If traffic is empty
    # we cannot produce a useful plot, but we can still generate an HTML
    # report — the report agent will fall back to "no traffic signal"
    # for the missing sections.
    plot_path = generate_plot(traffic, asn, start, end)
    if plot_path:
        traffic["plot_path"] = plot_path

    # Run the report generator. We pass the precomputed correlation so
    # the deterministic Evidence Chain can show real ΔT entries instead
    # of "(no data)".
    reasoning_result = {"correlation_analysis": correlation}

    try:
        from agents.report_agent import generate_report_html
        html_path = generate_report_html(
            asn=asn,
            start_time=start,
            end_time=end,
            traffic_result=traffic,
            routing_result=routing,
            reasoning_result=reasoning_result,
            output_dir=str(OUTPUT_DIR),
        )
    except Exception as e:
        tb = traceback.format_exc()
        return {
            "event_id": event_id, "asn": asn, "status": "fail",
            "reason": f"generate_report_html raised: {e}",
            "traceback": tb,
        }

    if not html_path or not Path(html_path).exists():
        return {
            "event_id": event_id, "asn": asn, "status": "fail",
            "reason": "generate_report_html returned empty path",
        }

    elapsed = round(time.time() - t0, 1)
    return {
        "event_id": event_id, "asn": asn, "status": "ok",
        "html_path": html_path, "elapsed_s": elapsed,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=0, help="process only first N events (0 = all)")
    ap.add_argument("--only-missing", action="store_true",
                    help="skip events that already have an HTML in results/html/")
    ap.add_argument("--max-duration-hours", type=float, default=6.0,
                    help="skip events with duration_hours above this")
    args = ap.parse_args()

    if not GT_CSV.exists():
        print(f"FATAL: {GT_CSV} missing", file=sys.stderr)
        return 1

    rows = list(csv.DictReader(GT_CSV.open()))
    print(f"Loaded {len(rows)} events from {GT_CSV.name}")
    if args.limit:
        rows = rows[:args.limit]

    if args.only_missing:
        existing = {p.stem.split("_AS")[-1].rsplit("_", 2)[0]
                    for p in OUTPUT_DIR.glob("llm_report_AS*.html")}
        # crude filter — we will just re-check inside process_event
        print(f"only-missing: {len(existing)} existing reports in {OUTPUT_DIR.name}/")

    summary = []
    t_run = time.time()
    for i, row in enumerate(rows, 1):
        dur = float(row.get("duration_hours", 0) or 0)
        if dur > args.max_duration_hours:
            print(f"  [{i:>2}/{len(rows)}] SKIP {row['event_id']}: duration {dur}h > {args.max_duration_hours}h")
            continue

        if args.only_missing:
            asn = pick_target_as(row)
            stem_pat = f"llm_report_AS{asn}_"
            has = any(p.name.startswith(stem_pat) for p in OUTPUT_DIR.glob("llm_report_*.html"))
            if has:
                print(f"  [{i:>2}/{len(rows)}] SKIP {row['event_id']} AS{asn}: already has HTML")
                continue

        print(f"  [{i:>2}/{len(rows)}] {row['event_id']} (AS={pick_target_as(row)}, {dur}h) ...", flush=True)
        rec = process_event(row, LOG_DIR / f"{row['event_id']}.log")
        status = rec["status"]
        rec["event_id"] = row["event_id"]
        rec["duration_hours"] = dur
        summary.append(rec)
        if status == "ok":
            print(f"             OK ({rec['elapsed_s']}s) -> {rec['html_path']}")
        elif status == "skip":
            print(f"             SKIP: {rec.get('reason','')}")
        else:
            print(f"             FAIL: {rec.get('reason','')}")
            if "traceback" in rec:
                (LOG_DIR / f"{row['event_id']}.log").write_text(rec["traceback"])

    # Write summary
    summary_path = LOG_DIR / "summary.jsonl"
    with summary_path.open("w", encoding="utf-8") as f:
        for r in summary:
            f.write(json.dumps(r, default=str, ensure_ascii=False) + "\n")

    ok = sum(1 for r in summary if r["status"] == "ok")
    fail = sum(1 for r in summary if r["status"] == "fail")
    skip = sum(1 for r in summary if r["status"] == "skip")
    elapsed = round(time.time() - t_run, 1)
    print()
    print("=" * 60)
    print(f"Total: {len(summary)} events in {elapsed}s")
    print(f"  OK:   {ok}")
    print(f"  FAIL: {fail}")
    print(f"  SKIP: {skip}")
    print(f"  Summary: {summary_path}")
    return 0 if fail == 0 else 2


if __name__ == "__main__":
    raise SystemExit(main())
